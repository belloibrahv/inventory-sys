export function titleFor(pathname: string) {
  if (pageTitles[pathname]) return pageTitles[pathname]
  const match = Object.keys(pageTitles).find((key) => pathname.startsWith(`${key}/`))
  return match ? pageTitles[match] : "Abu Twins"
}
